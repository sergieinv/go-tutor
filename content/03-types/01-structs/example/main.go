// Структура — набор именованных полей. Это тип-значение:
// присваивание копирует все поля, а ссылочную семантику
// получают явно, через указатель.

package main

import "fmt"

// Тип объявляется на уровне пакета. Поля с большой
// буквы видны из других пакетов, с маленькой — нет.
type User struct {
	Name  string
	Age   int
	Admin bool
}

type Point struct {
	X, Y int
}

func main() {

	// Литерал с именами полей: порядок не важен,
	// пропущенные поля получают нулевые значения.
	alice := User{Name: "Alice", Age: 30}
	fmt.Printf("%+v\n", alice)

	// Нулевое значение структуры — все поля нулевые.
	// Это обычное готовое значение, а не `null`.
	var empty User
	fmt.Printf("%+v %q\n", empty, empty.Name)

	// Присваивание копирует структуру целиком:
	// изменение `bob` не затрагивает `alice`.
	bob := alice
	bob.Name = "Bob"
	fmt.Println(alice.Name, bob.Name)

	// `==` сравнивает поля по одному. Это работает,
	// пока все поля сравнимы (нет срезов, map, функций).
	fmt.Println(Point{1, 2} == Point{X: 1, Y: 2})

	// Указатель на структуру: `&T{...}` создаёт значение
	// и сразу берёт его адрес. Поле читается как `p.X` —
	// Go сам разыменовывает, писать `(*p).X` не нужно.
	p := &Point{X: 3, Y: 4}
	p.X = 30
	fmt.Println(p.X, (*p).Y)

	// Через указатель меняется исходное значение.
	q := p
	q.Y = 40
	fmt.Println(*p)

	// `new(T)` выделяет нулевое значение и возвращает
	// указатель — то же самое, что `&T{}`.
	z := new(Point)
	fmt.Println(*z, *z == Point{})

	// Анонимная структура: тип без имени. Удобна для
	// разовых данных — табличных тестов, JSON-ответов.
	cfg := struct {
		Host string
		Port int
	}{"localhost", 8080}
	fmt.Printf("%s:%d\n", cfg.Host, cfg.Port)

	// Срез анонимных структур — типичная таблица случаев.
	cases := []struct {
		in   int
		want string
	}{{1, "one"}, {2, "two"}}
	for _, c := range cases {
		fmt.Println(c.in, c.want)
	}
}
