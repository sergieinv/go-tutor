// Массив — последовательность фиксированной длины.
// Длина входит в тип: `[3]int` и `[4]int` — разные
// типы. И главное: массив — значение, а не ссылка.

package main

import "fmt"

func main() {

	// Объявленный массив сразу заполнен нулевыми
	// значениями. `len` — длина, известная ещё
	// на этапе компиляции.
	var a [5]int
	fmt.Println("zero:", a, "len:", len(a))

	a[4] = 100
	fmt.Println("set:", a, "a[4]:", a[4])

	// В литерале `[...]` длину считает компилятор.
	// Можно задавать элементы по индексам — остальные
	// получат нулевые значения.
	b := [...]string{"go", "c#", "rust"}
	c := [...]string{3: "z", 1: "x"}
	fmt.Println("literal:", b, len(b))
	fmt.Printf("indexed: %q %d\n", c, len(c))

	// Присваивание копирует все элементы.
	// Изменения копии не видны в оригинале.
	d := b
	d[0] = "GO"
	fmt.Println("copy:", b[0], d[0])

	// Передача в функцию — тоже копия.
	double(a)
	fmt.Println("after double:", a)

	// Чтобы функция меняла массив, передают указатель.
	// Индексация через указатель на массив работает
	// без явного разыменования.
	doubleInPlace(&a)
	fmt.Println("after doubleInPlace:", a)

	// `==` сравнивает массивы поэлементно. Сравнивать
	// можно только массивы одного типа — то есть
	// с одинаковой длиной.
	x := [3]int{1, 2, 3}
	y := [3]int{1, 2, 3}
	fmt.Println("equal:", x == y)

	// Многомерный массив — массив массивов.
	// Он целиком лежит в памяти одним блоком.
	var grid [2][3]int
	for i := range 2 {
		for j := range 3 {
			grid[i][j] = i*3 + j
		}
	}
	fmt.Println("grid:", grid)

	// `x[:]` даёт срез, который смотрит в тот же
	// массив. Запись через срез меняет массив —
	// это мост к следующему уроку.
	s := x[:]
	s[0] = 42
	fmt.Println("via slice:", x)
}

func double(a [5]int) {
	for i := range a {
		a[i] *= 2
	}
}

func doubleInPlace(a *[5]int) {
	for i := range a {
		a[i] *= 2
	}
}
