// Rotate возвращает поле, повёрнутое на 90° по часовой стрелке.
// Исходное поле не меняется.
func Rotate(b [3][3]byte) [3][3]byte {
	// b — уже копия, но писать в неё нельзя: исходные
	// значения нужны до конца. Результат — новый массив.
	var r [3][3]byte
	for i := range 3 {
		for j := range 3 {
			r[j][2-i] = b[i][j]
		}
	}
	return r
}

// Winner возвращает 'X' или 'O', если у игрока три знака в ряд
// (строка, столбец или диагональ), иначе '.'.
func Winner(b [3][3]byte) byte {
	// Линии — массив из восьми троек координат.
	lines := [8][3][2]int{
		{{0, 0}, {0, 1}, {0, 2}},
		{{1, 0}, {1, 1}, {1, 2}},
		{{2, 0}, {2, 1}, {2, 2}},
		{{0, 0}, {1, 0}, {2, 0}},
		{{0, 1}, {1, 1}, {2, 1}},
		{{0, 2}, {1, 2}, {2, 2}},
		{{0, 0}, {1, 1}, {2, 2}},
		{{0, 2}, {1, 1}, {2, 0}},
	}
	for _, l := range lines {
		c := b[l[0][0]][l[0][1]]
		if c != '.' && c == b[l[1][0]][l[1][1]] && c == b[l[2][0]][l[2][1]] {
			return c
		}
	}
	return '.'
}
