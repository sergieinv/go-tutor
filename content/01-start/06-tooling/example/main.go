// Компилятор проверяет типы, но не смысл форматной
// строки: для него это просто `string`. Пример показывает,
// что печатает `fmt`, когда формат и аргументы
// не сходятся, — именно такие места находит `go vet`.

package main

import "fmt"

func main() {

	// Правильный вызов: каждому вербу — свой аргумент
	// подходящего типа. `%%` — знак процента.
	fmt.Printf("%s: %d%%\n", "готово", 50)

	// Вербы с флагами, шириной и точностью тоже
	// потребляют по одному аргументу.
	fmt.Printf("[%-6s] [%6.2f] [%+d] [%#x]\n", "go", 3.14159, 5, 255)

	// Вербу `%d` достался `string`. Паники нет: `fmt`
	// вставляет в вывод метку `%!d(тип=значение)`.
	// `go vet`: format %d has arg "пять" of wrong type string.
	fmt.Printf("%d товаров\n", "пять")

	// Аргументов меньше, чем вербов: на месте лишнего
	// верба появится `%!s(MISSING)`.
	// `go vet`: format %s reads arg #2, but call has 1 arg.
	fmt.Printf("%s и %s\n", "чай")

	// Аргументов больше: лишние дописываются в конец
	// вывода — после всего, что было в формате.
	// `go vet`: call needs 1 arg but has 2 args.
	fmt.Printf("%d", 1, 2)
	fmt.Println()

	// `Println` не форматирует — `%d` печатается как есть.
	// `go vet`: Println call has possible Printf formatting
	// directive %d.
	fmt.Println("итого: %d", 42)

	// `Sprintf` без использования результата ничего не делает.
	// Такую строку `go vet` тоже отметит: result of
	// fmt.Sprintf call not used. Правильно — присвоить.
	msg := fmt.Sprintf("%v и %v", true, 1.5)
	fmt.Println(msg)

	// `%v` подходит к любому типу, а `%T` печатает тип —
	// удобно, когда не уверены, что передаёте.
	fmt.Printf("%v %T\n", []int{1, 2}, map[string]int{})
}
