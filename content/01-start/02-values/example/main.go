// Базовые типы Go — строки, целые разного размера,
// числа с плавающей точкой и `bool`. Их значения
// никогда не превращаются друг в друга сами:
// любое преобразование пишется явно.

package main

import (
	"fmt"
	"strconv"
)

func main() {

	// Строки складываются через `+`. Строка неизменяема,
	// `len` возвращает длину в байтах UTF-8.
	fmt.Println("go" + "lang")
	fmt.Println(len("Go"), len("Го"))

	// Целые и дробные литералы, арифметика как в C#.
	// Деление целых отбрасывает дробную часть.
	fmt.Println("7/2 =", 7/2, "7%2 =", 7%2)
	fmt.Println("7.0/2 =", 7.0/2)

	// Логические значения и операции `&&`, `||`, `!`.
	fmt.Println(true && false, true || false, !true)

	// Целые фиксированного размера. `int` на 64-битной
	// платформе — 64 бита, `byte` — это `uint8`.
	var small int8 = 127
	var big int64 = 1 << 40
	var b byte = 'A'
	fmt.Println(small, big, b)

	// Смешивать типы нельзя: `small + big` не скомпилируется.
	// Преобразование выглядит как вызов: `T(x)`.
	sum := int64(small) + big
	fmt.Println("sum:", sum)

	// `float64` в целое — усечение к нулю.
	f := 3.99
	fmt.Println(int(f), int(-f))

	// Строки и числа связывает пакет `strconv`.
	n, err := strconv.Atoi("42")
	fmt.Println(n+1, err)
	fmt.Println(strconv.Itoa(n) + "!")

	// Вербы `fmt`: `%v` — значение в формате по умолчанию,
	// `%T` — тип, `%d` — целое, `%q` — строка в кавычках.
	fmt.Printf("%v %v %v\n", 42, 3.5, "hi")
	fmt.Printf("%T %T %T %T\n", 42, 3.5, "hi", 'x')
	fmt.Printf("%d %q %q\n", 42, "hi", 'x')

	// Ширина, точность и основание: `%5d` дополняет
	// пробелами, `%.2f` — два знака, `%x` — шестнадцатеричное,
	// `%08b` — двоичное с ведущими нулями.
	fmt.Printf("[%5d] [%.2f] [%x] [%08b]\n", 42, 3.14159, 255, 5)
}
