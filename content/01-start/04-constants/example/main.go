// Константа — значение, известное при компиляции.
// Нетипизированные константы Go не привязаны к типу,
// пока не встретятся с конкретным типом, и считаются
// с произвольной точностью.

package main

import (
	"fmt"
	"math"
)

// Константы можно объявлять на уровне пакета и группой.
// Здесь `KiB` — нетипизированная целая константа.
const (
	appName = "go-tutor"
	KiB     = 1 << 10
	MiB     = KiB << 10
)

// Типизированная константа ведёт себя как значение
// своего типа и в другой тип сама не превратится.
const maxRetries int8 = 3

func main() {
	fmt.Println(appName, KiB, MiB)

	// Нетипизированная константа подходит любому
	// числовому типу, в который помещается.
	var a int64 = KiB
	var b float64 = KiB
	var c uint16 = KiB
	fmt.Println(a, b, c)

	// Типизированную — только с явным преобразованием:
	// `var r int = maxRetries` не скомпилируется.
	r := int(maxRetries)
	fmt.Printf("%d %T\n", r, maxRetries)

	// Константное выражение — тоже константа. `1 << 100`
	// не помещается ни в один тип, но в промежуточных
	// вычислениях это не мешает.
	const huge = 1 << 100
	fmt.Println(huge >> 98)

	// Вещественные константы считаются точно, поэтому
	// здесь нет ошибки округления, привычной для `double`.
	const third = 1.0 / 3
	fmt.Println(third*3 == 1)

	// Целые константы делятся нацело, даже если результат
	// потом присваивается `float64`.
	var half float64 = 1 / 2
	var realHalf float64 = 1.0 / 2
	fmt.Println(half, realHalf)

	// Встроенные функции от константных аргументов,
	// например `len` строковой константы, — тоже константы.
	const nameLen = len(appName)
	fmt.Println("len:", nameLen)

	// `math.Pi` — нетипизированная константа. В выражении
	// с `float32` она станет `float32`, без потери типа.
	var radius float32 = 2
	area := math.Pi * radius * radius
	fmt.Printf("%.2f %T\n", area, area)
}
