// Пакет — каталог с файлами, модуль — дерево пакетов
// с `go.mod`. Пример однофайловый, поэтому показывает
// то, что видно изнутри одного пакета: импорты,
// инициализацию и видимость по регистру первой буквы.

package main

// Путь импорта и имя пакета — разные вещи. Пакет
// `math/rand` в коде называется `rand`, а `encoding/json` —
// `json`. Псевдоним задаёт другое имя, а `_` импортирует
// пакет только ради побочных эффектов его `init`.
import (
	"encoding/json"
	"fmt"
	str "strings"
	_ "time/tzdata"
)

// Имя с заглавной буквы экспортируется из пакета.
// Для пакета `main` это ничего не меняет, но для
// библиотечного пакета `Order` был бы виден снаружи,
// а `discount` — только файлам этого же пакета.
type Order struct {
	ID       int
	Customer string
	discount int
}

// Переменные пакета инициализируются до `main` в порядке
// зависимостей: `total` зависит от `base`, поэтому
// `base` вычисляется первой, хотя объявлена ниже.
var total = base * 2
var base = loadBase()

func loadBase() int {
	fmt.Println("1. инициализация переменных пакета")
	return 50
}

// `init` выполняется после переменных и до `main`.
// Функций `init` в пакете может быть несколько,
// вызвать их явно нельзя.
func init() {
	fmt.Println("2. init")
}

func main() {
	fmt.Println("3. main, total =", total)

	// К членам другого пакета обращаются через его имя
	// (или псевдоним). Видны только экспортированные:
	// `str.ToUpper` есть, а `strings.indexFunc` — нет.
	fmt.Println(str.ToUpper("go"), str.Repeat("-", 3))

	// Видимость работает и для полей. `encoding/json` —
	// другой пакет, поэтому `discount` он не видит
	// и молча пропускает.
	o := Order{ID: 7, Customer: "Аня", discount: 10}
	b, err := json.Marshal(o)
	fmt.Println(string(b), err)

	// Внутри своего пакета неэкспортированное поле
	// доступно как обычно.
	fmt.Println("discount:", o.discount)
}
