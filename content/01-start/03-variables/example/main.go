// Переменные в Go объявляются через `var` или `:=`.
// Тип пишется после имени, а неинициализированная
// переменная получает нулевое значение своего типа.

package main

import "fmt"

// На уровне пакета работает только `var` — короткая
// форма `:=` здесь не разрешена.
var greeting = "привет"

func main() {

	// Полная форма: имя, тип, значение.
	var a int = 10
	fmt.Println("a:", a)

	// Тип можно опустить — его выведет компилятор.
	var b = 2.5
	fmt.Printf("b: %v (%T)\n", b, b)

	// Значение можно опустить — будет нулевое значение.
	// `null` у строк и чисел нет.
	var (
		n     int
		s     string
		ok    bool
		ratio float64
	)
	fmt.Printf("zero: %d %q %t %v\n", n, s, ok, ratio)

	// Короткая форма `:=` — объявление с выводом типа.
	// Работает только внутри функций.
	name := "Go"
	year := 2009
	fmt.Println(greeting, name, year)

	// Несколько переменных за раз — и в `var`, и в `:=`.
	x, y := 1, 2
	fmt.Println("x, y:", x, y)

	// Множественное присваивание: сначала вычисляется
	// вся правая часть, потом присваивается. Поэтому
	// обмен значений не требует временной переменной.
	x, y = y, x
	fmt.Println("swap:", x, y)

	// `:=` с уже существующей переменной допустим, если
	// слева есть хотя бы одна новая. Старая получает
	// новое значение, а не объявляется заново.
	x, z := 100, 3
	fmt.Println("x, z:", x, z)

	// Во вложенном блоке `:=` создаёт новую переменную,
	// которая затеняет внешнюю. Внешняя не меняется.
	if x > 0 {
		x := "строка"
		fmt.Println("inner x:", x)
	}
	fmt.Println("outer x:", x)

	// Пустой идентификатор `_` отбрасывает значение.
	// Неиспользуемая локальная переменная —
	// ошибка компиляции, а `_` — нет.
	_, second := 1, 2
	fmt.Println("second:", second)
}
