// Fib возвращает n-е число Фибоначчи: Fib(0) = 0, Fib(1) = 1.
// Для n < 0 — 0. Должна быстро работать для n до 90.
func Fib(n int) int {
	a, b := 0, 1
	for range max(n, 0) {
		// Правая часть вычисляется целиком до присваивания.
		a, b = b, a+b
	}
	return a
}

// GCD возвращает наибольший общий делитель a и b
// (всегда неотрицательный). GCD(0, 0) = 0.
func GCD(a, b int) int {
	for b != 0 {
		a, b = b, a%b
	}
	// Остаток от деления отрицательного числа отрицателен,
	// поэтому знак результата может быть любым.
	if a < 0 {
		a = -a
	}
	return a
}
