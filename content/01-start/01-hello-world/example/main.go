// Каждый исполняемый Go-файл начинается с объявления
// пакета. Программа — это пакет `main`: только из него
// `go build` собирает исполняемый файл.

package main

// `import` подключает пакеты. Здесь `fmt` — форматированный
// ввод-вывод, аналог `Console` и `string.Format`.
import (
	"fmt"
	"strings"
)

// Функция верхнего уровня — без класса-обёртки. Её
// можно вызвать из `main` или из любой функции пакета.
func greet(name string) string {
	return "Привет, " + name + "!"
}

// `main` — точка входа. Без параметров и без результата:
// аргументы командной строки берут из `os.Args`,
// код возврата задают через `os.Exit`.
func main() {

	// `Println` печатает аргументы через пробел
	// и добавляет перевод строки.
	fmt.Println("Hello, World")
	fmt.Println(greet("Go"))

	// Аргументы могут быть любых типов: `fmt` сам
	// подберёт представление для числа и `bool`.
	fmt.Println("версия", 1.25, "готово:", true)

	// `Printf` — форматная строка с вербами. `%s` — строка,
	// `%d` — целое, `\n` нужно ставить самому.
	fmt.Printf("%s изучает Go %d-й день\n", "Аня", 3)

	// `Sprintf` возвращает строку, а не печатает её —
	// это ближайший аналог интерполяции `$"..."`.
	line := fmt.Sprintf("%d + %d = %d", 2, 2, 2+2)
	fmt.Println(line)

	// Вызов функции из другого пакета — всегда через имя
	// пакета. `using static` в Go нет.
	fmt.Println(strings.ToUpper("громко"))
	fmt.Println(strings.Repeat("=", 10))
}
