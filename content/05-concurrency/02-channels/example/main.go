// Канал — типизированная труба между горутинами.
// Небуферизованный канал — точка встречи: отправитель
// ждёт получателя, получатель ждёт отправителя,
// и значение переходит из рук в руки.

package main

import (
	"fmt"
	"strings"
)

// Канал — ссылочный тип, как map: функция получает копию
// дескриптора, но работает с тем же каналом.
func shout(words []string, out chan string) {
	for _, w := range words {
		out <- strings.ToUpper(w) // ждёт, пока main заберёт значение
	}
}

func main() {

	// `make(chan T)` создаёт небуферизованный канал.
	// Нулевое значение канала — `nil`, им пользоваться нельзя.
	ch := make(chan string)

	// Отправка `ch <- v` блокирует горутину, пока другая
	// не выполнит получение `<-ch`. Поэтому отправляем
	// из отдельной горутины: в одной `main` отправка
	// ждала бы вечно.
	go func() {
		ch <- "привет"
	}()

	// Получение тоже блокирует — до прихода значения.
	// Когда `<-ch` вернулось, отправка уже состоялась:
	// канал одновременно передаёт данные и синхронизирует.
	msg := <-ch
	fmt.Println("получено:", msg)

	// Канал как способ вернуть результат из горутины —
	// вместо `Task<T>`.
	sum := make(chan int)
	go func() {
		total := 0
		for i := 1; i <= 100; i++ {
			total += i
		}
		sum <- total
	}()
	fmt.Println("сумма 1..100:", <-sum)

	// Значения приходят в том порядке, в котором их
	// отправили: канал — очередь FIFO. Получаем ровно
	// столько, сколько отправлено, — иначе одна из
	// сторон заблокируется навсегда.
	words := []string{"раз", "два", "три"}
	go shout(words, ch)
	for range words {
		fmt.Println(<-ch)
	}

	// Тип канала включает тип элемента: в `chan int`
	// строку не отправить — это ошибка компиляции.
	// Значения копируются, как при присваивании.
	type point struct{ X, Y int }
	pts := make(chan point)
	p := point{1, 2}
	go func() { pts <- p }()
	q := <-pts
	q.X = 100
	fmt.Println("исходная:", p, "полученная:", q)
}
